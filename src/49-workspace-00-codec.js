/* Versioned, data-only laboratory snapshots. No persistence or DOM dependencies. */
'use strict';
(function () {
  const VERSION = 1;
  const MAX_BYTES = 8 * 1024 * 1024;
  const forbidden = new Set(['__proto__', 'prototype', 'constructor']);

  function data(value, depth = 0) {
    if (depth > 100) throw new Error('Estado excede a profundidade permitida.');
    if (value === null || ['string', 'boolean'].includes(typeof value)) return value;
    if (typeof value === 'number' && Number.isFinite(value)) return value;
    if (Array.isArray(value)) return value.map(v => data(v, depth + 1));
    if (value instanceof Map) return { $map: Array.from(value, ([k, v]) => [data(k, depth + 1), data(v, depth + 1)]) };
    if (value instanceof Set) return { $set: Array.from(value, v => data(v, depth + 1)) };
    if (value && typeof value === 'object' && Object.prototype.toString.call(value) === '[object Object]' && (!value.constructor || value.constructor.name === 'Object')) {
      const out = {};
      for (const [key, v] of Object.entries(value)) {
        if (forbidden.has(key)) throw new Error('Chave inválida no estado.');
        if (v !== undefined) out[key] = data(v, depth + 1);
      }
      return out;
    }
    throw new Error('Estado não serializável.');
  }

  function hydrate(value) {
    if (!value || typeof value !== 'object') return value;
    if (Array.isArray(value)) return value.map(hydrate);
    if (Object.keys(value).length === 1 && Array.isArray(value.$map)) return new Map(value.$map.map(([k, v]) => [hydrate(k), hydrate(v)]));
    if (Object.keys(value).length === 1 && Array.isArray(value.$set)) return new Set(value.$set.map(hydrate));
    const out = {};
    for (const [k, v] of Object.entries(value)) {
      if (forbidden.has(k)) throw new Error('Chave inválida no snapshot.');
      out[k] = hydrate(v);
    }
    return out;
  }
  const fields = (object, names) => {
    const out = {};
    for (const key of names.split(' ')) if (object[key] !== undefined) out[key] = data(object[key]);
    return out;
  };

  const inodeFields = 'ino type mode uid gid atime mtime ctime btime nlink blocks content target major minor immutable acl aclGroupObj defaultAcl tamanhoComprimido';
  LX.FileSystem.prototype.exportState = function () {
    const seen = new Map(), nodes = [];
    const visit = (node, path) => {
      if (seen.has(node)) return seen.get(node);
      const id = nodes.length;
      seen.set(node, id);
      const row = { data: fields(node, inodeFields), path };
      nodes.push(row);
      // Runtime /proc entries are regenerated by the fresh kernel.
      if (node.type === 'dir') row.children = Array.from(node.children)
        .filter(([name]) => !(path === '/proc' && /^\d+$/.test(name)))
        .map(([name, child]) => [name, visit(child, (path === '/' ? '' : path) + '/' + name)]);
      if (node.dynamic) { row.dynamic = true; delete row.data.content; }
      return id;
    };
    return { root: visit(this.root, '/'), nodes, metadata: fields(this, 'mounts totalBlocks usedBlocks somenteLeitura tmpfs') };
  };

  LX.FileSystem.prototype.importState = function (snapshot) {
    if (!snapshot || !Array.isArray(snapshot.nodes) || !snapshot.nodes.length || snapshot.nodes.length > 100000) throw new Error('Sistema de arquivos inválido.');
    const runtime = new Map();
    const collect = (node, path) => {
      if (node.dynamic || node.dynDir) runtime.set(path, node);
      if (node.type === 'dir') for (const [name, child] of node.children) collect(child, (path === '/' ? '' : path) + '/' + name);
    };
    collect(this.root, '/');
    const nodes = snapshot.nodes.map(row => {
      if (!row.data || !['dir', 'file', 'link', 'chr', 'blk', 'fifo', 'sock'].includes(row.data.type)) throw new Error('Inode inválido.');
      const base = runtime.get(row.path);
      // Keep the actual /proc inode: kernel closures hold this reference.
      const node = base || new LX.Inode(row.data.type, row.data.mode);
      Object.assign(node, hydrate(fields(row.data, inodeFields)));
      if (row.dynamic && !base?.dynamic) throw new Error('Arquivo dinâmico desconhecido.');
      if (node.type === 'dir') node.children = new Map();
      node.parent = null;
      delete node.aliases;
      return node;
    });
    const attached = new Set();
    snapshot.nodes.forEach((row, i) => {
      if (row.data.type !== 'dir') return;
      if (!Array.isArray(row.children)) throw new Error('Diretório inválido.');
      for (const [name, id] of row.children) {
        if (typeof name !== 'string' || !name || /[/\0]/.test(name) || name === '.' || name === '..' || !Number.isInteger(id) || !nodes[id]) throw new Error('Entrada de diretório inválida.');
        const child = nodes[id];
        if (nodes[i].children.has(name) || (child.type === 'dir' && attached.has(id))) throw new Error('Referência duplicada.');
        nodes[i].children.set(name, child);
        if (child.parent) (child.aliases ||= []).push({ parent: nodes[i], name });
        else { child.parent = nodes[i]; child.name = name; }
        attached.add(id);
      }
    });
    const root = nodes[snapshot.root];
    if (!root || root.type !== 'dir' || root.parent) throw new Error('Raiz inválida.');
    const visited = new Set();
    const walk = (node, depth = 0) => {
      if (depth > 100) throw new Error('Árvore inválida.');
      if (visited.has(node)) return;
      visited.add(node);
      if (node.type === 'dir') for (const child of node.children.values()) walk(child, depth + 1);
    };
    walk(root);
    if (visited.size !== nodes.length) throw new Error('Inodes desconectados.');
    this.root = root;
    root.name = '';
    Object.assign(this, hydrate(snapshot.metadata));
    // Inodes created after restore must not reuse a persisted number.
    LX.reserveInodes(Math.max(...nodes.map(n => n.ino)) + 1);
    return this;
  };

  const shellFields = 'vars arrays funcs aliases cwd uid gid user umask lastStatus pipestatus opts shopts history dirstack positional scriptName nomeShell traps pid lastBgPid container remote';
  LX.Shell.prototype.exportState = function () { return fields(this, shellFields); };
  LX.Shell.prototype.importState = function (snapshot) {
    Object.assign(this, hydrate(fields(snapshot, shellFields)));
    if (typeof this.cwd !== 'string' || !this.m.fs.exists(this.cwd)) throw new Error('Diretório do shell indisponível.');
    this.jobs = []; // JavaScript jobs cannot be resumed across browser processes.
    return this;
  };

  // Git's canonical state is already a VFS file, including index and stash.
  LX.Git.exportState = () => ({ format: 'vfs', repositoryFile: '.git/terminalis.json' });
  LX.Git.importState = state => {
    if (state?.format !== 'vfs' || state.repositoryFile !== '.git/terminalis.json') throw new Error('Formato Git não suportado.');
  };
  LX.Github.exportState = machine => data(machine.gitHub || { repos: {}, auth: null });
  LX.Github.importState = (machine, snapshot) => { machine.gitHub = hydrate(snapshot); };

  LX.Workspace = { VERSION, MAX_BYTES, data, hydrate, fields };
})();
